import assert from 'node:assert/strict';
import {finishEstimate} from '../docs/finish-estimate.mjs';
const now=10000,stats={startedAt:now-1200,expiresAt:now+20000,lastFixAt:now-10,distanceMeters:3218.688};
const match={remainingMeters:8*1609.344};
let r=finishEstimate(stats,match,now);assert.equal(r.secondsRemaining,4800);assert.equal(r.finishAt,now+4800);
assert.equal(finishEstimate({...stats,distanceMeters:0},match,now),null);
assert.equal(finishEstimate({...stats,lastFixAt:now-181},match,now),null);
assert.equal(finishEstimate({...stats,expiresAt:now},match,now),null);
assert.equal(finishEstimate(stats,null,now),null);
assert.equal(finishEstimate(stats,{remainingMeters:0},now).secondsRemaining,0);
assert.equal(finishEstimate(stats,{...match,alongMiles:90},now).secondsRemaining,4800);
console.log('Passed: remaining duration, finish clock time, actual-distance pace, missing data, stale fixes and expiry.');
